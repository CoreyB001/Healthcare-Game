def icon_for(category: str, behavior: str) -> str:
    lower = behavior.lower()
    for term, icon in KEYWORDS:
        if term in lower:
            return icon
    return CATEGORY_EMOJI[category]


def generate() -> list[list[str | int]]:
    output = []
    seen = set()
    for path, polarity in SOURCES:
        with path.open(newline="", encoding="utf-8-sig") as stream:
            reader = csv.DictReader(stream)
            if reader.fieldnames != ["Category", "Behavior", "Points"]:
                raise ValueError(f"Unexpected CSV columns in {path.name}: {reader.fieldnames}")
            for line, row in enumerate(reader, 2):
                category, behavior = row["Category"].strip(), row["Behavior"].strip()
                score = int(row["Points"])
                if not category or not behavior or category not in CATEGORY_EMOJI:
                    raise ValueError(f"Invalid category/behavior at {path.name}:{line}")
                if score * polarity <= 0:
                    raise ValueError(f"Incorrect score sign at {path.name}:{line}")
                key = (category, behavior, score)
                if key in seen:
                    raise ValueError(f"Duplicate CSV entry at {path.name}:{line}")
                seen.add(key)
                output.append([icon_for(category, behavior), behavior, score, category])
    if len(output) != 288:
        raise ValueError(f"Expected 288 rows across the supplied CSVs; got {len(output)}")
    return output


